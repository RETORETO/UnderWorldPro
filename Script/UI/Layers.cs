namespace Script.UI
{
    /// <summary>
    /// 【2026-10·UI 层级唯一真相源】战场（Arena / ArenaOl）所有 `ZIndex` 的分配与**可扩展区间**。
    ///
    /// 背景（为什么必须有这张表）：
    ///   · 旧代码里层级是散落各处的魔数（100 / 1000 / 4095 / 4096 / 4100 …）。Godot 的 `z_index`
    ///     有 **±4096** 的硬上限，超过会被截断/丢弃 —— 这正是"命令框设了 4100 却仍被压住"的根因；
    ///   · 层级散落后，想在"某两层之间插入新东西"必须先把全工程翻一遍，改一处极易踩到另一处。
    ///
    /// 本表把全部层级压进 **1000 以内**，并按"用途分带 + 带间留空"的方式给出扩展位。
    /// **新增任何 UI 元素时必须从本表取层号，禁止再写魔数。**
    ///
    /// ── 分带总览（数值越大越在上层）────────────────────────────────────────────
    ///   0    –   99   世界容器/窗口自身（Arena 根、ArenaOl 根、ScrollContainer、滑块等）
    ///   100  –  199   地区/场地区域  ★扩展：地区附属、地区标记、地区级高亮 → 150~199
    ///   200  –  299   区域槽位内部（AreaSlot 自身、AreaCardUI 内部分层）
    ///   300  –  399   卡牌本体（场上/手牌/资产/秘社/牌库/墓地）★扩展：卡面装饰、状态角标 → 380~399
    ///   400  –  499   卡牌拖拽态（拖拽中的卡必须压住其它卡）★扩展：拖拽残影、工具提示 → 450~499
    ///   500  –  599   附属/封印/堆叠等"依附类"（相对宿主层级做偏移）
    ///   600  –  699   区域容器（牌库/墓地/堆叠面板与其中复制的卡 UI）
    ///   800  –  899   浮层（卡面悬浮预览、箭头层、结果/计数/得分标签）★扩展：835~849、860~899
    ///   900  –  999   最上层交互（PM 命令输入框）★扩展：900 以下留给"命令框之下、浮层之上"的新浮层
    ///   1000+        **不要使用**（超出 1000 的层级既无必要，又逼近 Godot 上限）
    ///
    /// ── 插入新层级的推荐做法 ───────────────────────────────────────────────────
    ///   ① 先在上表找到"用途最接近的那一带"，用该带内的**空号**（注释里的 ★扩展 已标出区间）；
    ///   ② 若某带确实排满，再从**带间空隙**取值（如 199→200、299→300、399→400、499→500、
    ///      599→600、699→800、899→900 都是空档）；
    ///   ③ 取值后**必须**在本文件补一个具名常量并写清它与相邻常量的高低关系，
    ///      不要在使用处直接写字面量。
    /// </summary>
    public static class Layers
    {
        // ==================== 世界容器 / 窗口自身（0–99）====================
        /// <summary>战场根节点自身（`Arena` / `ArenaOl`）。</summary>
        public const int WorldRoot = 0;

        // ==================== 地区 / 场地区域（100–199）====================
        /// <summary>争夺区槽位背景（`AreaSlot`；多槽时按索引递增，右槽压左槽）。</summary>
        public const int AreaSlotBase = 100;

        /// <summary>争夺区"地区胜利标记"等地区级附加物。【预留】现无使用者，扩展取 150~199。</summary>
        public const int AreaDecoration = 150;

        // ==================== 区域槽位内部（200–299）====================
        /// <summary>地区卡 UI（`AreaCardUI`）在自身槽位内垫高一层，压住槽位背景装饰。</summary>
        public const int AreaCardInner = 210;

        // ==================== 卡牌本体（300–399）====================
        /// <summary>卡牌基准层（场上/手牌/资产/秘社/牌库/墓地）。
        /// 实际值＝`CardBase + 布局序号`（右卡压左卡），布局序号远小于 100，故卡牌整体落在本带内。</summary>
        public const int CardBase = 300;

        /// <summary>卡牌拖拽态：拖拽中的卡必须压住其它所有卡。【预留】扩展取 450~499。</summary>
        public const int CardDragging = 400;

        // ==================== 附属 / 封印 / 堆叠依附类（500–599）====================
        /// <summary>附属卡相对其宿主的层级偏移基数（`宿主层 - 偏移`，即附属压在宿主**之上**）。</summary>
        public const int AttachedBadgeBase = 500;

        /// <summary>封印卡相对被封印卡的层级偏移基数（封印卡压在目标之上）。</summary>
        public const int SealedBadgeBase = 550;

        /// <summary>堆叠面板内"复制的地区卡 UI"：压住面板文字层。</summary>
        public const int StackPanelCard = 580;

        // ==================== 区域容器（600–699）====================
        /// <summary>牌库/墓地等区域容器内的卡 UI（按索引递增）。</summary>
        public const int ZoneCardBase = 600;

        /// <summary>区域容器的计数/标题标签（牌库张数、堆叠张数等）。</summary>
        public const int ZoneOverlayLabel = 650;

        // ==================== 浮层（800–899）====================
        /// <summary>箭头层（堆叠目标箭头、激活拖拽箭头）：压住所有卡与附属。</summary>
        public const int Arrows = 800;

        /// <summary>卡面悬浮预览（鼠标悬停整张卡图）：**高于箭头层**（旧实现即为预览压箭头）。
        /// ★扩展：835~849 预留给"新的全屏绘制类浮层"。</summary>
        public const int CardHoverPreview = 830;

        /// <summary>结果/状态大标签（如"游戏结果"提示）。</summary>
        public const int ResultLabel = 850;

        /// <summary>计数/得分叠层标签（`CountLabel` / `ScoreLabel`，牌库张数等）。</summary>
        public const int StatsLabel = 860;

        // ==================== 最上层交互（900–999）====================
        /// <summary>PM 命令输入框：**战场内最高层**（必须压住秘社卡与卡面悬浮预览）。</summary>
        public const int CommandInput = 900;

        // ==================== 说明：模态窗口不占用本表 ====================
        // 调查/战斗/破平/触发排序/选目标等弹窗的根节点都是 Godot `Window`（独立子窗口），
        // 由引擎保证"永远在最上层"，其内部子控件的 ZIndex 只需在**该窗口内部**保持相对高低，
        // 因此它们用独立的小整数命名空间，既不影响战场层级、也不占用 0~1000 的预算。

        /// <summary>【窗口内部层】触发排序窗内被拖拽的条目：必须高于该窗口内的
        /// `OrderZoneContainer`（现为 1000），故取窗口局部命名空间的 1500。
        /// 它只在触发排序 `Window` 内部生效，与战场层级（0~1000）互不干扰。</summary>
        public const int TriggerOrderDrag = 1500;
    }
}
